        # The local pickle is generated by our own verified ranking run, never uploaded input.
        with gzip.open(parent/f'snapshot-{origin}.pkl.gz','rb') as f:bundle=pickle.load(f)
        s=bundle['snapshot'];queries=bundle['queries'];rows={};summaries={};training={};t=time.perf_counter();weights=ease_weights(s['x'],cfg['ease_regularization'])
        summaries['ease'],rows['ease']=evaluate(s,queries,lambda q:(s['x'].getrow(s['ui'][q['customer']])@weights).ravel()[q['ids']]);training['ease']={'seconds':time.perf_counter()-t}
        np.save(run/f'ease-{origin}.npy',weights)
        for seed in cfg['graph']['seeds']:
            t=time.perf_counter();model,uf,it,loss=fit_graph(s['x'],cfg['graph'],seed,config['threads']);name=f'lightgcn_{seed}'
            checkpoint=run/f'{name}-{origin}.pt';torch.save(model.state_dict(),checkpoint)
            loaded=LightGCN(*s['x'].shape,cfg['graph']['dimensions'],cfg['graph']['layers']);loaded.load_state_dict(torch.load(checkpoint,weights_only=True));loaded.eval()
            with torch.no_grad():u2,i2=loaded.propagate(normalized_graph(s['x']))
