def normalized_graph(x):
    rows,cols=x.nonzero();nu,ni=x.shape;cols=cols+nu
    src=np.concatenate([rows,cols]);dst=np.concatenate([cols,rows]);degree=np.bincount(src,minlength=nu+ni)
    values=1/np.sqrt(np.maximum(degree[src]*degree[dst],1))
    return torch.sparse_coo_tensor(torch.tensor(np.stack([src,dst]),dtype=torch.long),torch.tensor(values,dtype=torch.float32),(nu+ni,nu+ni)).coalesce()

class LightGCN(torch.nn.Module):
    def __init__(self,users,items,dimensions,layers):
        super().__init__();self.users=users;self.layers=layers
        self.embedding=torch.nn.Embedding(users+items,dimensions)
        torch.nn.init.normal_(self.embedding.weight,std=.1)
    def propagate(self,adjacency):
        out=self.embedding.weight;layers=[out]
        for _ in range(self.layers):out=torch.sparse.mm(adjacency,out);layers.append(out)
        all_layers=torch.stack(layers).mean(dim=0)
        return all_layers[:self.users],all_layers[self.users:]

def negative_items(x,users,rng):
    n=x.shape[1];neg=rng.integers(0,n,len(users));invalid=np.asarray(x[users,neg]).ravel()>0
    for _ in range(20):
        if not invalid.any():return neg
        neg[invalid]=rng.integers(0,n,int(invalid.sum()));invalid=np.asarray(x[users,neg]).ravel()>0
    for pos in np.flatnonzero(invalid):
        available=np.setdiff1d(np.arange(n),x.getrow(users[pos]).indices,assume_unique=True)
        if not len(available):raise ValueError('No unobserved item for this user')
        neg[pos]=rng.choice(available)
    return neg

def fit_graph(x,cfg,seed,threads=2):
    torch.set_num_threads(threads);torch.manual_seed(seed);rng=np.random.default_rng(seed)
    adjacency=normalized_graph(x);model=LightGCN(*x.shape,cfg['dimensions'],cfg['layers']);optimizer=torch.optim.Adam(model.parameters(),lr=cfg['learning_rate'])
    users,items=x.nonzero();eligible=np.asarray(x.sum(axis=1)).ravel()<x.shape[1];mask=eligible[users];users=users[mask];items=items[mask]
    if not len(users):raise ValueError('No usable graph training edges')
    trace=[]
    for epoch in range(cfg['epochs']):
        order=rng.permutation(len(users));total=0.;count=0
        for start in range(0,len(order),cfg['batch_size']):
            batch=order[start:start+cfg['batch_size']];u=users[batch];p=items[batch];n=negative_items(x,u,rng)
            uf,it=model.propagate(adjacency);positive=(uf[u]*it[p]).sum(-1);negative=(uf[u]*it[n]).sum(-1)
            regularization=(model.embedding(torch.tensor(u)).square().sum()+model.embedding(torch.tensor(p+x.shape[0])).square().sum()+model.embedding(torch.tensor(n+x.shape[0])).square().sum())/(2*len(batch))
            loss=torch.nn.functional.softplus(negative-positive).mean()+cfg['regularization']*regularization
            optimizer.zero_grad();loss.backward();optimizer.step();total+=loss.item()*len(batch);count+=len(batch)
        trace.append(total/count)
    model.eval()
    with torch.no_grad():uf,it=model.propagate(adjacency)
    return model,uf.numpy(),it.numpy(),trace

def ease_weights(x,regularization):
    gram=(x.T@x).toarray().astype(float);gram.flat[::len(gram)+1]+=regularization
    precision=linalg.solve(gram,np.eye(len(gram)),assume_a='pos',check_finite=False);w=-precision/np.diag(precision)[None,:];np.fill_diagonal(w,0)
    return w

